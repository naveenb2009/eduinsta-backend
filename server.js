/* Within a page, best matches first (title > subject > category > text). */
function rankSearch(list,q){
  const terms=q.split(/\s+/).filter(Boolean);
  return list.map(r=>{
    const title=(r.title||"").toLowerCase(), sub=(r.sub||"").toLowerCase(), cat=(r.cat||"").toLowerCase();
    const desc=(r.desc||"").toLowerCase(), creator=(r.creator||"").toLowerCase();
    let score=0;
    terms.forEach(t=>{
      if(title.includes(t))score+=8; if(sub.includes(t))score+=7; if(cat.includes(t))score+=6;
      if(desc.includes(t))score+=4; if(creator.includes(t))score+=2;
    });
    return {r,score};
  }).filter(x=>x.score>0).sort((a,b)=>b.score-a.score).map(x=>x.r);
}
async function runSearch(){
  const q=(document.getElementById("searchInput")?.value||"").trim().toLowerCase();
  const results=document.getElementById("searchResults"); if(!results)return;
  if(!q){searchStream=null;results.innerHTML='<div class="empty">Start typing to search.</div>';return}
  const st=makeStream({q},r=>rankSearch([r],q).length>0);
  st.q=q; searchStream=st;
  try{await streamNext(st,STREAM_PAGE)}
  catch{if(searchStream===st)results.innerHTML='<div class="empty">Search is temporarily unavailable.</div>';return}
  if(searchStream!==st)return;      // a newer search replaced this one
  if(!st.items.length){
    results.innerHTML=`<div class="empty">No reels found for "${escapeHtml(q)}".<br><br>Try a subject, technology, exam, creator or topic.</div>`;
    return;
  }
  results.innerHTML=rankSearch(st.items,q).map(searchReelHTML).join("")
    +(st.exhausted?'':`<button type="button" class="loadMoreBtn" id="searchMore" onclick="loadMoreSearch()">Load more results</button>`);
  activateThumbs(results);
}
