/* Every page renderer calls this first so the stack knows where we are. */
function markPage(fn){currentPageFn=fn}
/* Navigate to a sub-page, remembering where we came from. */
function goTo(fn){
  if(currentPageFn&&currentPageFn!==fn)navStack.push(currentPageFn);
  if(navStack.length>20)navStack.shift();
  fn();
}
/* Go back to wherever we actually came from. */
function navBack(fallbackFn){
  const prev=navStack.pop();
  if(prev){currentPageFn=prev;prev();return}
  (fallbackFn||(()=>page('profile')))();
}
/* Switching top-level tabs resets the stack - you're starting a new journey. */
function resetNav(){navStack=[];currentPageFn=null}

