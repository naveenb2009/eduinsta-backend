/* ---- One-time-password (OTP) infrastructure ----
   There is no backend or SMS/email provider wired into this static prototype,
   so delivery is SIMULATED: the "sent" code is surfaced via toast instead of a
   real message. Everything else (expiry, attempt limits, resend, verify) works
   exactly like a real OTP flow, so swapping in a real provider (e.g. an SMS/
   email API called from a backend) later only means replacing the body of
   sendOtp() - every caller and the UI around it stay the same. */
var pendingOtp=null; // {code,target,purpose,expiresAt,attempts}
const OTP_TTL_MS=5*60*1000, OTP_MAX_ATTEMPTS=5;
async function sendOtp(target,purpose){
  if(serverMode()){
    /* SERVER MODE: the backend generates and emails/SMSes the code. It is
       never sent back here, so it cannot be read out of the page. */
    pendingOtp={target,purpose,server:true};
    try{
      const res=await fetch(`${API_BASE}/api/send-otp`,{
        method:'POST',headers:{'Content-Type':'application/json'},
        body:JSON.stringify({target})
      });
      const data=await res.json();
      if(!data.ok){toast(data.error||'Could not send the code');return null}
      toast(`Verification code sent to ${target}`);
    }catch{
      toast('Could not reach the server. Check your connection.');
    }
    return null;
  }
  /* PROTOTYPE MODE: no backend configured, so the code is shown on screen. */
  const code=String(Math.floor(100000+Math.random()*900000));
  pendingOtp={code,target,purpose,expiresAt:Date.now()+OTP_TTL_MS,attempts:0};
  showOtpBanner(code,target);
  return code;
}
