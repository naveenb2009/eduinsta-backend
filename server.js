function saveSubscription(){lsSet('er_subscription',JSON.stringify(subscription))}
/* Runs on every read of subscription status. If a paid period has actually
   elapsed (per stored timestamps) since we last checked, this either
   auto-renews (simulating a successful recurring charge) or, if the user
   already cancelled, flips the status to expired. In production this
   reconciliation would be driven by the payment provider's webhook/receipt,
   not just a local timestamp - this is the offline-prototype stand-in for
   that server-side verification step. */
function checkSubscriptionExpiry(){
  if(subscription.status==='active'&&subscription.expiresAt&&Date.now()>subscription.expiresAt){
    if(subscription.cancelAtPeriodEnd){
      subscription.status='expired';
      subscription.history=[...(subscription.history||[]),{type:'expired',at:Date.now()}];
      saveSubscription();
      addNotification('system','Subscription expired','Your EduInsta Premium has expired. Renew anytime from Premium settings.');
    }else{
      subscription.expiresAt=Date.now()+PREMIUM_CONFIG.billingCycleDays*86400000;
      subscription.renewsAt=subscription.expiresAt;
      subscription.history=[...(subscription.history||[]),{type:'renewed',at:Date.now(),planId:subscription.planId}];
      saveSubscription();
      addNotification('system','Subscription renewed',`Your EduInsta Premium was renewed for another ${PREMIUM_CONFIG.billingCycleDays} days.`);
    }
  }
}
function isPremium(){checkSubscriptionExpiry();return subscription.status==='active'}

/* In SERVER MODE the server is the authority on subscription status. This runs
   at boot and after every payment, so editing localStorage to fake Premium is
   overwritten on the next launch. In prototype mode it is a no-op. */
async function refreshSubscriptionFromServer(){
  if(!serverMode())return;
  try{
    const res=await fetch(`${API_BASE}/api/subscription/${encodeURIComponent(currentUserId())}`);
    if(!res.ok)return;
    const data=await res.json();
    subscription.status=data.status||'free';
    subscription.expiresAt=data.expiresAt||null;
    subscription.renewsAt=data.expiresAt||null;
    saveSubscription();
  }catch{ /* offline: keep the cached value rather than locking the user out */ }
  await applyPlayEntitlement();
}
/* On Android, Google Play (through RevenueCat) is the source of truth for
   Premium. The server's copy only updates when a webhook arrives, so without
   this a server restart or a delayed webhook made a paying user look free. */
async function applyPlayEntitlement(){
  if(!PurchasesService.available())return;
  const ent=await PurchasesService.currentEntitlement();
  if(!ent)return;                                   // couldn't check - keep what we have
  if(ent.active){
    subscription.status='active';
    subscription.expiresAt=ent.expiresAt||subscription.expiresAt||Date.now()+30*86400000;
    subscription.renewsAt=subscription.expiresAt;
  }else if(subscription.status==='active'){
    subscription.status='expired';
  }
  saveSubscription();
}

/* ---- Payment gateway (SIMULATED) ----
   In production this would load the Razorpay Checkout.js SDK
   (https://checkout.razorpay.com/v1/checkout.js), create a secure order via a
   backend endpoint, and open Razorpay's real hosted checkout, then verify the
   payment signature server-side. No backend or live payment keys exist in
   this static prototype, so checkout is simulated locally with explicit
   Pay / Fail / Cancel outcomes, which also makes every outcome
   deterministically testable (a real gateway's result can't be).
   Used for ADVERTISER CAMPAIGN payments only (a B2B purchase, not a
   consumer digital good, so Play Store policy is fine with a third-party
   gateway here). The Premium subscription no longer uses this path -- see
   PurchasesService / Google Play Billing above. Includes a standard set of
   payment methods (Card / UPI / Net Banking / Wallet), same as any
   mainstream Indian payment gateway offers. */
var __checkoutOnCancel=null;
function openCheckout(opts){
  if(serverMode())return openRealCheckout(opts);
  return openSimulatedCheckout(opts);
}
/* SERVER MODE: create the order on the backend (which decides the real
   amount), open Razorpay's hosted sheet, then verify the signature
   server-side. Premium is granted only if that verification passes. */
async function openRealCheckout({title,amount,type,days,onSuccess,onFailure,onCancel}){
  if(typeof Razorpay==='undefined'){
    toast('Payment library not loaded — add the Razorpay script tag');
    onFailure&&onFailure(); return;
  }
  try{
    const orderRes=await fetch(`${API_BASE}/api/create-order`,{
      method:'POST',headers:{'Content-Type':'application/json'},
      body:JSON.stringify({type:type||'premium',userId:currentUserId(),days})
    });
    if(!orderRes.ok)throw new Error('order failed');
    const order=await orderRes.json();
    const rzp=new Razorpay({
      key:order.keyId, amount:order.amount, currency:order.currency,
      name:'EduInsta', description:title, order_id:order.orderId,
      prefill:{email:account.email||'',contact:profile.phone||''},
      theme:{color:'#5eead4'},
      handler:async function(response){
        const v=await fetch(`${API_BASE}/api/verify-payment`,{
          method:'POST',headers:{'Content-Type':'application/json'},
          body:JSON.stringify({...response,userId:currentUserId(),type:type||'premium',days})
        });
        const result=await v.json();
        if(result.ok){await refreshSubscriptionFromServer();onSuccess(response.method||'card')}
        else onFailure();
      },
      modal:{ondismiss:function(){onCancel&&onCancel()}}
    });
    rzp.on('payment.failed',function(){onFailure()});
    rzp.open();
  }catch(err){
    console.error(err); toast('Could not start checkout'); onFailure&&onFailure();
  }
}
