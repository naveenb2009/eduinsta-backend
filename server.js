/* ---- Earnings model ----
   Revenue has two sources: Premium subscription payments and advertiser
   campaign payments. Both are read from records the app already keeps
   (subscription.history and adCampaigns), so the dashboard reflects real
   recorded transactions rather than invented numbers. Payment-gateway fees
   are estimated so the owner sees net, not just gross. */
const GATEWAY_FEE_RATE=0.0236; // ~2% + 18% GST, typical Indian gateway rate
function computeEarnings(){
  const subPayments=(subscription.history||[]).filter(h=>h.type==='purchased'||h.type==='renewed');
  const subGross=subPayments.reduce((sum,h)=>sum+(h.price||PREMIUM_CONFIG.plan.price),0);
  const adPayments=adCampaigns.filter(c=>c.price);
  const adGross=adPayments.reduce((sum,c)=>sum+c.price,0);
  const gross=subGross+adGross;
  const fees=Math.round(gross*GATEWAY_FEE_RATE);
  const now=Date.now(), monthAgo=now-30*86400000;
  const recent=[
    ...subPayments.filter(h=>h.at>=monthAgo).map(h=>({at:h.at,amount:h.price||PREMIUM_CONFIG.plan.price})),
    ...adPayments.filter(c=>c.startAt>=monthAgo).map(c=>({at:c.startAt,amount:c.price}))
  ];
  return {
    subGross,adGross,gross,fees,net:gross-fees,
    subCount:subPayments.length,adCount:adPayments.length,
    last30:recent.reduce((s,r)=>s+r.amount,0),
    transactions:[
      ...subPayments.map(h=>({at:h.at,type:'Premium subscription',amount:h.price||PREMIUM_CONFIG.plan.price,method:h.method||'—'})),
      ...adPayments.map(c=>({at:c.startAt,type:'Ad campaign — '+c.sponsor,amount:c.price,method:c.method||'—'}))
    ].sort((a,b)=>b.at-a.at)
  };
}
