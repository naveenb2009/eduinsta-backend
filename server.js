/* Call BEFORE a new account's session is written. Restores that account's
   own data if it has signed in on this phone before, otherwise starts clean.
   Signing back into the same account keeps everything as it is. */
function switchUserData(newEmail){
  const cur=lsGetRaw('er_active_user')||'';
  if(cur && norm(cur)===norm(newEmail||''))return;
  /* Before this update there was no er_active_user: the plain keys belong to
     whoever was last signed in (account) or registered (registeredAccount). */
  const legacyEmail=cur?'':((account&&account.email)||(registeredAccount&&registeredAccount.email)||'');
  const bucket=readJSON(userBucketKey(newEmail),null);
  const legacyOwner=!cur && !bucket && legacyEmail && norm(legacyEmail)===norm(newEmail||'');
  if(cur)stashUserData(cur);
  else if(legacyEmail && !legacyOwner)stashUserData(legacyEmail);
  if(!legacyOwner){
    USER_DATA_KEYS.forEach(k=>{try{localStorage.removeItem(k)}catch{}});
    if(bucket)Object.keys(bucket).forEach(k=>lsSet(k,bucket[k]));
  }
  lsSet('er_active_user',newEmail||'');
  reloadUserStateFromStorage();
}
function logout(){
  const leaving=account&&account.email;
  if(leaving){
    stashUserData(leaving);
    USER_DATA_KEYS.forEach(k=>{try{localStorage.removeItem(k)}catch{}});
    try{localStorage.removeItem('er_active_user')}catch{}
    reloadUserStateFromStorage();
  }
  account={loggedIn:false,email:"",name:""};
  lsSet('er_account',JSON.stringify(account));
  PurchasesService.signOut();
  closeOverlay(); toast("Logged out");
  renderAuthGate('login');
}

