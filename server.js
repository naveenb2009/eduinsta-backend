/* ---------------- Shared creator avatars ----------------
   Profile photos live on the server now (see setAvatar/getAvatars in
   reels-service.js), so any user's feed can show another creator's real
   photo, not just their own. Avatars are fetched in a small batched,
   debounced call (one request per feed page, not one per reel) and cached
   client-side for the rest of the session; the DOM is patched in place
   once each batch resolves rather than blocking the feed render. */
var creatorAvatars={};
var __avatarFetchQueue=new Set();
var __avatarFetchTimer=null;
function queueAvatarFetch(creator){
  if(!creator || Object.prototype.hasOwnProperty.call(creatorAvatars,creator) || !serverMode())return;
  __avatarFetchQueue.add(creator);
  if(__avatarFetchTimer)return;
  __avatarFetchTimer=setTimeout(flushAvatarFetch,60);
}
async function flushAvatarFetch(){
  __avatarFetchTimer=null;
  const ids=[...__avatarFetchQueue]; __avatarFetchQueue.clear();
  if(!ids.length)return;
  try{
    const res=await fetch(`${API_BASE}/api/avatars?ids=${encodeURIComponent(ids.join(','))}`);
    const data=await res.json();
    if(!data.ok)return;
    ids.forEach(id=>{creatorAvatars[id]=data.avatars[id]||null});
    applyAvatarsToDom(ids);
  }catch{ids.forEach(id=>{delete creatorAvatars[id]})}
}
function avatarSpanHTML(creator){
  const initial=escapeHtml(String(creator||'?').replace(/^@/,'').charAt(0).toUpperCase()||'?');
  const url=creatorAvatars[creator];
  if(url)return `<span class="reelAvatar" data-creator="${escapeAttr(creator)}"><img src="${escapeAttr(url)}" alt=""></span>`;
  queueAvatarFetch(creator);
  return `<span class="reelAvatar" data-creator="${escapeAttr(creator)}" aria-hidden="true">${initial}</span>`;
}
function applyAvatarsToDom(creators){
  creators.forEach(c=>{
    const url=creatorAvatars[c];
    if(!url||typeof CSS==='undefined'||!CSS.escape)return;
    document.querySelectorAll(`.reelAvatar[data-creator="${CSS.escape(c)}"]`).forEach(el=>{
      el.innerHTML=`<img src="${escapeAttr(url)}" alt="">`;
      el.removeAttribute('aria-hidden');
    });
  });
}

