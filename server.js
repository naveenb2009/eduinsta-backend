const EMAIL_RE=/^[^\s@]+@[^\s@]+\.[^\s@]+$/;
const PHONE_RE=/^\+?[0-9]{7,15}$/;
function isValidEmail(v){return EMAIL_RE.test(String(v||'').trim())}
function isValidPhone(v){return PHONE_RE.test(String(v||'').trim())}
function isValidIdentifier(v){v=String(v||'').trim();return isValidEmail(v)||PHONE_RE.test(v)}
function digitsOnly(v){return String(v||'').replace(/\D/g,'')}

/* ---- Password policy ----
   8-32 characters, must start with a letter, and must contain at least one
   number and one special character. Enforced everywhere a password is
   CREATED (signup, reset) - not on login, which only ever checks it against
   what's already stored. */
const PASSWORD_MIN=8, PASSWORD_MAX=32;
function isValidPassword(pw){
  pw=String(pw||'');
  if(pw.length<PASSWORD_MIN||pw.length>PASSWORD_MAX)return false;
  if(!/^[A-Za-z]/.test(pw))return false;      // must start with a letter
  if(!/[0-9]/.test(pw))return false;          // at least one number
  if(!/[^A-Za-z0-9]/.test(pw))return false;   // at least one special character
  return true;
}
const PASSWORD_HINT=`${PASSWORD_MIN}-${PASSWORD_MAX} characters, start with a letter, and include at least one number and one special character.`;

function maskEmail(email){
  const [user,domain]=String(email||'').split('@');
  if(!domain)return email||'';
  return `${user.slice(0,1)}${'*'.repeat(Math.max(2,user.length-1))}@${domain}`;
}
function maskPhone(phone){
  const d=digitsOnly(phone);
  return d.length<4?(phone||''):`••••${d.slice(-4)}`;
}

