/* Which channel an identifier implies. One field, two possible kinds. */
function identifierType(v){
  v=String(v||'').trim();
  if(isValidEmail(v))return 'email';
  if(isValidPhone(v))return 'phone';
  return null;
}
function validateSignupFields({name,identifier,password,confirmPassword}){
  name=(name||'').trim(); identifier=(identifier||'').trim();
  password=password||''; confirmPassword=confirmPassword||'';
  const errors={};
  if(name.length<2)errors.name='Enter your full name.';
  /* Signup is email-only. SMS OTP needs TRAI DLT registration in India, so
     phone numbers are added later in Settings and verified by email instead. */
  if(!isValidEmail(identifier))errors.identifier='Enter a valid email address.';
  if(!isValidPassword(password))errors.password='Password must be '+PASSWORD_HINT;
  if(confirmPassword!==password)errors.confirmPassword='Passwords do not match.';
  return Object.keys(errors).length?{ok:false,errors}:{ok:true};
}
/* Accounts are now real server-side records (see /api/signup in server.js) -
   previously this only ever wrote to THIS device's local storage, which is
   wiped on reinstall, so "sign in" would stop working even though the user
   never asked to delete anything. Server mode requires connectivity to
   create an account (it always did require it to actually be useful across
   devices); the local copy below is kept too, purely as an offline-login
   cache once you've successfully signed in on this device at least once. */
async function performSignup({name,identifier,password}){
  name=(name||'').trim(); identifier=(identifier||'').trim();
  let signupToken=null;
  if(serverMode()){
    try{
      const res=await fetch(`${API_BASE}/api/signup`,{
        method:'POST',headers:{'Content-Type':'application/json'},
        body:JSON.stringify({name,email:identifier,password})
      });
      const data=await res.json();
      if(!data.ok)return{ok:false,exists:res.status===409||/already exists/i.test(data.error||''),error:data.error||'Could not create your account. Please try again.'};
      signupToken=data.token||null;
    }catch{
      return{ok:false,error:'Could not reach the server. Check your connection and try again.'};
    }
  }
  /* A signup creates a FRESH account record. Do NOT inherit the email or phone
     of whoever was registered before - that would leak the previous user's
     contact details into the new account and let them receive its OTPs. */
  switchUserData(identifier);
  registeredAccount={name,password,email:identifier,phone:null};
  profile.phone=null;
  lsSet('er_registered_account',JSON.stringify(registeredAccount));
  account={loggedIn:true,email:registeredAccount.email||registeredAccount.phone,name,...(signupToken?{token:signupToken}:{})};
  lsSet('er_account',JSON.stringify(account));
  profile.name=name;
  profile.username="@"+name.toLowerCase().replace(/[^a-z0-9]+/g,"").slice(0,20)||"@student";
  saveState();
  addNotification('system','Welcome to EduInsta 🎉','Your account was created successfully.');
  addNotification('learning','Personalize your feed','Pick a few interests in your profile to fine-tune your For You feed.');
  syncOwnAvatarFromServer();
  return{ok:true};
}
async function performLogin({identifier,password}){
  identifier=(identifier||'').trim(); password=password||'';
  if(!identifier||!password)return{ok:false,error:'Enter your email/mobile and password.'};

  if(serverMode()){
    try{
      const res=await fetch(`${API_BASE}/api/login`,{
        method:'POST',headers:{'Content-Type':'application/json'},
        body:JSON.stringify({email:identifier,password})
      });
      const data=await res.json();
      if(data.ok){
        switchUserData(identifier);
        registeredAccount={name:data.name||identifier,password,email:identifier,phone:data.phone||null};
        lsSet('er_registered_account',JSON.stringify(registeredAccount));
        account={loggedIn:true,email:identifier,name:data.name||identifier,...(data.token?{token:data.token}:{})};
        lsSet('er_account',JSON.stringify(account));
        if(!profile.name||profile.name==='Your Name')profile.name=data.name||identifier;
        if(!profile.username||profile.username==='@student')profile.username="@"+String(profile.name).toLowerCase().replace(/[^a-z0-9]+/g,"").slice(0,20)||"@student";
        if(data.phone)profile.phone=data.phone;
        saveState();
        addNotification('security','New sign-in','Your account was signed in on this device.');
        syncOwnAvatarFromServer();
        return{ok:true};
      }
      /* The server definitively said "wrong password" - trust that and stop,
         rather than falling through to a stale local check that could let
         an old/changed password still work. */
      if(res.status===401)return{ok:false,error:data.error||'Incorrect email/mobile or password.'};
      // status 404 (no such account on the server yet - see the migration
      // fallback below) or a server error - fall through.
    }catch{
      // Server unreachable - fall through to the offline check below.
    }
  }

  /* OFFLINE FALLBACK, and MIGRATION PATH for accounts created before this
     update shipped (the server has never heard of them, but this device's
     local copy is still valid). A successful local match here silently
     creates the matching server record too, so future logins - including
     after a reinstall - work without the user having to do anything. */
  if(!registeredAccount)return{ok:false,error:serverMode()?'Could not reach the server. Check your connection and try again.':'No account found on this device yet — please sign up first.'};
  const matchesEmail=norm(identifier)===norm(registeredAccount.email);
  const idDigits=digitsOnly(identifier);
  const matchesPhone=!!registeredAccount.phone && idDigits.length>=7 && idDigits===digitsOnly(registeredAccount.phone);
  if(!(matchesEmail||matchesPhone)||password!==registeredAccount.password)
    return{ok:false,error:'Incorrect email/mobile or password.'};
  switchUserData(registeredAccount.email);
  account={loggedIn:true,email:registeredAccount.email,name:registeredAccount.name};
  lsSet('er_account',JSON.stringify(account));
  if(!profile.name||profile.name==='Your Name')profile.name=registeredAccount.name;
  saveState();
  addNotification('security','New sign-in','Your account was signed in on this device.');
  syncOwnAvatarFromServer();
  if(serverMode()){
    fetch(`${API_BASE}/api/signup`,{
      method:'POST',headers:{'Content-Type':'application/json'},
      body:JSON.stringify({name:registeredAccount.name,email:registeredAccount.email,phone:registeredAccount.phone,password:registeredAccount.password})
    }).catch(()=>{});
  }
  return{ok:true};
}

