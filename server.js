const A11Y_KEYS=['largeText','highContrast','reducedMotion','captions'];
function toggleSetting(key,btn){
  /* Read the CURRENT displayed state off the button itself rather than
     re-deriving it from erGet() with a guessed default - the row may have
     been rendered with a default of true, and a mismatched default here
     would silently no-op the very first tap on an "on-by-default" switch. */
  const next=!btn.classList.contains('on');
  erSet(key,next);
  btn.classList.toggle('on',next);
  if(A11Y_KEYS.includes(key))applyAccessibilitySettings();
  toast(next?'Enabled':'Disabled');
}
