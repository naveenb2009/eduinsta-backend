/* Premium goes through Play Billing on a native build (PurchasesService,
   above) -- Razorpay/the simulated sheet is only used as a browser preview
   fallback where Play Billing can't run, purely so the flow is still
   click-through-able while developing in a plain browser tab. Ad-campaign
   checkout (startAdCampaignCheckout, below) is untouched and keeps using
   openCheckout()/Razorpay -- that purchase type never moves to Play Billing. */
async function startCheckout(){
  const plan=PREMIUM_CONFIG.plan;
  if(PurchasesService.available()){
    try{
      const entitled=await PurchasesService.purchasePremium();
      if(!entitled){toast('Purchase completed but Premium isn\'t active yet — pull to refresh in a moment.');return}
      await refreshSubscriptionFromServer();   // includes Google Play's own record via RevenueCat
      syncAdMobWithSubscription();
      if(!isPremium()){
        // RevenueCat's webhook to our backend hasn't landed yet; the purchase
        // itself succeeded with Google, so tell the user rather than erroring.
        toast('Payment received — activating Premium…');
        setTimeout(async()=>{await refreshSubscriptionFromServer();premiumPage()},3000);
        return;
      }
      toast('🎉 Welcome to EduInsta Premium!');premiumPage();
    }catch(err){
      console.error(err);
      // RevenueCat's rejection carries a `userCancelled` boolean on Android;
      // string-matching the message is only a fallback for other shapes.
      if(err?.userCancelled||String(err?.message||err).toLowerCase().includes('cancel')){toast('Checkout cancelled');return}
      recordPaymentFailure();toast('Payment failed — please try again.');
    }
    return;
  }
  // Browser fallback (no native Play Billing available) -- preview only.
  openCheckout({
    title:plan.label,
    amount:plan.price,
    intervalLabel:plan.interval,
    type:'premium',
    onSuccess:(method)=>{activateSubscription(method);toast('🎉 Welcome to EduInsta Premium! (browser preview — real builds use Google Play Billing)');premiumPage()},
    onFailure:()=>{recordPaymentFailure();toast('Payment failed — please try again.')},
    onCancel:()=>{toast('Checkout cancelled')}
  });
}
