async function verifyOtpCode(input){
  if(!pendingOtp)return{ok:false,error:'No code was requested. Please request a new one.'};
  if(pendingOtp.server){
    /* SERVER MODE: verification happens on the backend, so the code can't be
       bypassed by editing anything in the browser. */
    try{
      const res=await fetch(`${API_BASE}/api/verify-otp`,{
        method:'POST',headers:{'Content-Type':'application/json'},
        body:JSON.stringify({target:pendingOtp.target,code:String(input||'').trim()})
      });
      const data=await res.json();
      if(data.ok)lastOtpTicket=data.ticket||null;
      return data.ok?{ok:true,purpose:pendingOtp.purpose,target:pendingOtp.target}
                    :{ok:false,error:data.error||'Incorrect code. Please try again.'};
    }catch{
      return{ok:false,error:'Could not reach the server. Check your connection.'};
    }
  }
  if(Date.now()>pendingOtp.expiresAt)return{ok:false,error:'This code has expired. Please request a new one.'};
  pendingOtp.attempts++;
  if(pendingOtp.attempts>OTP_MAX_ATTEMPTS)return{ok:false,error:'Too many incorrect attempts. Please request a new code.'};
  if(String(input||'').trim()!==pendingOtp.code)return{ok:false,error:'Incorrect code. Please try again.'};
  return{ok:true,purpose:pendingOtp.purpose,target:pendingOtp.target};
}
