/* Loads pages until `want` new reels arrived (or the end). Returns the new
   reels. Concurrent calls share the same request. Throws on a network error
   for the FIRST page so callers can show a retry message. */
function streamNext(s,want){
  if(s.busy)return s.busy;
  s.busy=(async()=>{
    const added=[];
    const take=list=>{for(const r of list){if(s.seen.has(r.id))continue;if(s.filter&&!s.filter(r))continue;s.seen.add(r.id);added.push(r)}};
    if(!serverMode()){
      if(!s.exhausted){take((await localReels()).reverse());s.exhausted=true}
    }else{
      let pages=0;
      while(!s.exhausted&&added.length<(want||STREAM_PAGE)&&pages<5){
        pages++;
        const qs=new URLSearchParams({limit:String(STREAM_PAGE)});
        Object.entries(s.params).forEach(([k,v])=>{if(v!=null&&v!=='')qs.set(k,v)});
        if(s.cursor)qs.set('cursor',s.cursor);
        let data;
        try{
          const res=await fetch(`${API_BASE}/api/feed?${qs}`);
          if(!res.ok)throw new Error('feed request failed');
          data=await res.json();
        }catch(err){if(!s.items.length&&!added.length)throw err;break}
        s.cursor=data.nextCursor||null;
        if(!data.nextCursor)s.exhausted=true;
        take((data.reels||[]).map(r=>({...r,src:resolveMediaUrl(r.src)})));
      }
    }
    s.items.push(...added);
    return added;
  })().finally(()=>{s.busy=null});
  return s.busy;
}
