/* SERVER MODE: the video is sent to the backend, where Gemini watches it and
   decides whether it is genuinely educational and safe. Publishing is gated
   on the verdict, and the verdict is issued server-side so it can't be
   skipped from the browser. */
async function runRealEducationCheck(file,title){
  const box=document.getElementById("check");
  box.innerHTML=`<div class="checkResult checkPending"><b>🔎 Analysing your video…</b><p>Our AI is watching the video to confirm it's educational. This usually takes 10–30 seconds.</p><div class="checkSpinner"></div></div>`;
  try{
    const form=new FormData();
    form.append('video',file);
    form.append('title',title);
    form.append('userId',currentUserId());
    const res=await fetch(`${API_BASE}/api/education-check`,{method:'POST',body:form,headers:authHeaders()});
    const verdict=await res.json();
    /* A request problem (signed out, wrong file type) is not a content
       verdict: explain it and keep the chosen video, don't discard it. */
    if(!res.ok&&verdict&&verdict.status==='error'){
      box.innerHTML=`<div class="checkResult checkFail"><b>⚠️ Couldn't check this video</b><p>${escapeHtml(verdict.reason||'Please try again.')}</p></div>`;
      return;
    }
    lastModerationVerdict=verdict;
    renderModerationVerdict(verdict);
  }catch(err){
    /* Fail OPEN, matching the server: a connectivity problem on our side
       shouldn't stop someone publishing. */
    console.error(err);
    lastModerationVerdict={status:'approved',approved:true,unreviewed:true};
    box.innerHTML=`<div class="checkResult checkPass"><b>✅ Ready to publish</b>
      <p>We couldn't reach the review service, so this was approved by default.</p></div>
      <button type="button" class="primary" onclick="publishUpload()">Publish Reel</button>`;
  }
}
