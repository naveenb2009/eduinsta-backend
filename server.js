/* Best-effort "when was this posted" in epoch ms, from whichever field the
   reel actually has:
     - server reels: a real createdAt ISO timestamp
     - local (prototype-mode) uploads: no createdAt, but id IS Date.now()
     - built-in demo/seed reels: small hand-picked negative ids (-1,-2,…),
       no useful time signal at all — treated as oldest, so they sink to
       the bottom below any real content instead of crowding out real
       uploads. */
function reelTimestamp(r){
  if(r.createdAt){
    const t=Date.parse(r.createdAt);
    if(!isNaN(t))return t;
  }
  if(typeof r.id==='number'){
    if(r.id>1e14)return Math.floor(r.id/1000);   // server id: Date.now()*1000+seq
    if(r.id>1e11)return r.id;                     // local upload id: Date.now()
  }
  return 0;                                       // demo/seed reel: no real date
}
/* Newest first, with reels from people you follow bumped above everyone
   else's (still newest-first within each group). Used by every home feed
   tab so a followed creator's new upload is never buried. */
function sortFeedByPriority(arr){
  return arr.slice().sort((a,b)=>{
    const af=following.includes(a.creator)?1:0;
    const bf=following.includes(b.creator)?1:0;
    if(af!==bf)return bf-af;
    return reelTimestamp(b)-reelTimestamp(a);
  });
}
/* ================= Feed paging & windowing =================
   Previously the feed built EVERY reel as a DOM node on every render, and
   re-read the whole of IndexedDB each time. That is fine at 6 reels and
   unusable at a few hundred: render time and memory both grow linearly.

   Two fixes, both local (no server needed):
     PAGING   — render PAGE_SIZE items, append more as the user nears the end
     WINDOWING— only reels near the viewport keep a loaded <video>; the rest
                have their src detached, so memory stays flat no matter how
                long the feed gets. */
const FEED_PAGE_SIZE=8;      // items rendered per page
const VIDEO_WINDOW=3;        // reels either side of current that keep their src
