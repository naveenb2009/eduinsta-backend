/* A <video> renders a black frame until it has loaded metadata AND seeked to
   a real frame — which is why thumbnails showed nothing but the play icon.
   Two things fix it:
     1. preload="metadata" so the browser fetches enough to decode a frame
     2. seeking slightly into the clip, because frame 0 is often black
   We append #t=0.5 (a media fragment) for normal URLs, and for blob: URLs —
   where fragments are unreliable — seek manually once metadata arrives. */
function thumbVideoHTML(src){
  const isBlob=String(src).startsWith('blob:');
  const finalSrc=isBlob?src:`${src}#t=0.5`;
  return `<video data-thumb-src="${escapeAttr(finalSrc)}" muted playsinline preload="metadata" onloadedmetadata="seekThumb(this)"></video>`;
}
/* Lazy thumbnails. Every thumbnail is a <video>, and phones cap how many
   video players a page may hold at once (Android WebView is stricter than
   desktop Chrome). Explore/Profile/Downloads render one per reel, so a big
   catalogue would exhaust that cap and later thumbnails would stay black.
   Only thumbnails near the screen get a src; ones scrolled far away release
   their player again. */
var thumbObserver=('IntersectionObserver' in window)?new IntersectionObserver(entries=>{
  entries.forEach(e=>{
    const v=e.target;
    if(e.isIntersecting){
      if(!v.getAttribute('src')&&v.dataset.thumbSrc)v.src=v.dataset.thumbSrc;
    }else if(v.getAttribute('src')){
      v.removeAttribute('src'); v.classList.remove('thumbReady');
      try{v.load()}catch{}
    }
  });
},{rootMargin:'600px 0px'}):null;
function activateThumbs(root){
  (root||document).querySelectorAll('video[data-thumb-src]:not([data-thumb-watched])').forEach(v=>{
    v.setAttribute('data-thumb-watched','1');
    if(thumbObserver)thumbObserver.observe(v); else v.src=v.dataset.thumbSrc;
  });
}
/* Release the decoder of any video that has left the page (screen change,
   feed reload). Browsers do this eventually on their own, but low-memory
   phones can run out of video players first. Checked a moment later so a
   video that is merely being moved in the DOM is left alone. */
function releaseRemovedVideos(nodes){
  const vids=[];
  nodes.forEach(n=>{ if(n.nodeType!==1)return; if(n.tagName==='VIDEO')vids.push(n); else if(n.querySelectorAll)vids.push(...n.querySelectorAll('video')); });
  if(!vids.length)return;
  setTimeout(()=>vids.forEach(v=>{
    if(v.isConnected)return;
    try{v.pause();v.removeAttribute('src');v.load()}catch{}
  }),0);
}
if('MutationObserver' in window){
  new MutationObserver(muts=>{
    let added=false; const removed=[];
    for(const m of muts){ if(m.addedNodes.length)added=true; if(m.removedNodes.length)removed.push(...m.removedNodes); }
    if(removed.length)releaseRemovedVideos(removed);
    if(added)activateThumbs(document);
  }).observe(document.documentElement,{childList:true,subtree:true});
}
function seekThumb(v){
  try{
    if(v.currentTime<0.1 && v.duration && isFinite(v.duration)){
      v.currentTime=Math.min(0.5, v.duration/2);
    }
  }catch{}
}
