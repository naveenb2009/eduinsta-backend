/* The server may hand back a RELATIVE video path (/api/video/...). Inside the
   Android app the page origin is localhost, so a relative path resolves to
   https://localhost/... and the video silently fails to load. Resolve any
   relative src against the API host so it points at the real server. */
function resolveMediaUrl(src){
  if(!src)return src;
  if(/^(https?:|blob:|data:)/i.test(src))return src;        // already absolute
  if(!API_BASE)return src;                                   // prototype mode
  return `${API_BASE.replace(/\/$/,'')}${src.startsWith('/')?'':'/'}${src}`;
}
/* ---------------- Reel streams (unlimited, Instagram-style) ----------------
   Every reel stays available until its uploader deletes it - there is NO cap
   on how many exist. The app never downloads "all reels"; it asks the server
   for one page (newest first) and asks for the next page as the user nears
   the end, exactly like Instagram Reels / YouTube Shorts. Home tabs, Explore
   chips and Search each use their own stream with their own server filter. */
const STREAM_PAGE=20;
function makeStream(params,filter){
  return {params:params||{},filter:filter||null,cursor:null,exhausted:false,items:[],seen:new Set(),busy:null};
}
