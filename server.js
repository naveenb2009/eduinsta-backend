/* Called whenever a reel starts playing. Shows an interstitial every
   `interstitialEvery` reels - deliberately much rarer than the in-feed
   sponsored slots, because interstitials interrupt and hurt retention. */
var reelsViewedSinceAd=0, lastAdCountedReelId=null;
function noteReelViewedForAds(id){
  if(isPremium()||!shouldShowAds()||!AdMobService.available())return;
  /* Full-screen AdMob ads: at most one per `interstitialEvery` DIFFERENT
     reels and never within `interstitialMinGapMinutes` of the last one.
     Pausing/resuming or replaying the same reel does not count again. */
  if(!AdConfig.interstitialsEnabled)return;
  if(id!=null&&id===lastAdCountedReelId)return;
  lastAdCountedReelId=id;
  reelsViewedSinceAd++;
  const every=Math.max(10,Number(AdConfig.interstitialEvery)||AD_DEFAULTS.interstitialEvery);
  if(reelsViewedSinceAd<every)return;
  /* Second gate: a minimum real-time gap. Reel count alone isn't enough -
     a fast scroller could otherwise hit several interstitials in a minute. */
  const gapMs=Math.max(1,Number(AdConfig.interstitialMinGapMinutes)||AD_DEFAULTS.interstitialMinGapMinutes)*60000;
  const last=Number(adState.lastInterstitialAt||0);
  if(Date.now()-last<gapMs)return;
  reelsViewedSinceAd=0;
  adState.lastInterstitialAt=Date.now();
  saveAdState();
  AdMobService.showInterstitial();
}

