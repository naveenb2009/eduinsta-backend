/* Fetches specific reels by id (e.g. saved/watch-history ids from local
   storage) directly, instead of hoping they're on whichever single feed
   page happens to already be loaded - a saved reel from a few days ago is
   very likely to have scrolled off the first page by now.

   Saved/liked/watched ids can point at TWO different kinds of reel:
     - a real, server-published reel               -> only the server knows it
     - one of the 6 built-in demo reels (ids 1-6)   -> only known locally,
                                                        never exists on the server
   Only checking the server (the old bug here) silently dropped every saved
   demo reel from the Saved tab, Downloads page and Watch history - they'd
   never come back even though `saved`/`watchHistory` still had their ids.
   So: ask the server for whichever ids it has, then fill in anything it
   didn't return (including when the server is unreachable) from the local
   demo list. Ids are normalized to numbers throughout so a save recorded
   from one source can't silently mismatch a lookup from the other. */
async function fetchReelsByIds(ids){
  if(!ids||!ids.length)return [];
  const wanted=ids.map(Number).filter(Number.isFinite);
  if(!wanted.length)return [];
  const byId=new Map();
  if(serverMode()){
    try{
      const res=await fetch(`${API_BASE}/api/reels/batch?ids=${encodeURIComponent(wanted.join(','))}`);
      const data=await res.json();
      if(data.ok){
        data.reels.forEach(r=>byId.set(Number(r.id),{...r,id:Number(r.id),src:resolveMediaUrl(r.src)}));
      }
    }catch(err){
      console.warn('Could not load reels by id from the server:',err);
    }
  }
  const missing=wanted.filter(id=>!byId.has(id));
  if(missing.length){
    /* Local built-in demo reels first (always in memory, no fetch needed);
       allReelsCached() also covers prototype/offline mode entirely. */
    reels.forEach(r=>{ if(!byId.has(r.id) && missing.includes(r.id)) byId.set(r.id,r) });
    const stillMissing=wanted.filter(id=>!byId.has(id));
    if(stillMissing.length){
      const all=await allReelsCached();
      all.forEach(r=>{ if(!byId.has(r.id) && stillMissing.includes(r.id)) byId.set(r.id,r) });
    }
  }
  return wanted.map(id=>byId.get(id)).filter(Boolean);
}

