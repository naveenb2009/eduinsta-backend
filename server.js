/* ================= Sharing =================
   navigator.share is often unavailable inside an Android WebView, which is why
   sharing silently fell back to "copied to clipboard" instead of opening the
   system share sheet. Three tiers, best first:
     1. Capacitor Share plugin  -> the real Android/iOS share sheet
                                   (WhatsApp, Instagram, Gmail, everything)
     2. navigator.share         -> the browser's own sheet, where supported
     3. clipboard / prompt      -> last resort so sharing is never a dead end */
function nativeSharePlugin(){
  return window.Capacitor?.isNativePlatform?.() ? (window.Capacitor.Plugins?.Share||null) : null;
}
async function shareContent({title,text,url,dialogTitle}){
  const payload={title,text,...(url?{url}:{}),dialogTitle:dialogTitle||'Share via'};
  const plugin=nativeSharePlugin();
  if(plugin){
    try{ await plugin.share(payload); return 'native'; }
    catch(err){
      /* The user closing the sheet also rejects — that is not a failure,
         and must not trigger a clipboard fallback behind their back. */
      if(String(err?.message||err).toLowerCase().includes('cancel'))return 'cancelled';
      console.warn('Native share failed, falling back:',err);
    }
  }
  if(navigator.share){
    try{ await navigator.share(payload); return 'web'; }
    catch(err){
      if(err?.name==='AbortError')return 'cancelled';
      console.warn('navigator.share failed, falling back:',err);
    }
  }
  const full=url?`${text} ${url}`:text;
  if(navigator.clipboard&&window.isSecureContext){
    try{ await navigator.clipboard.writeText(full); toast('Link copied — paste it anywhere'); return 'clipboard'; }catch{}
  }
  showShareFallbackSheet(full);
  return 'manual';
}
