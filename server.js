/* ================= Deep links =================
   Sharing a reel now points at <API_BASE>/reel/<id> (see shareReel above)
   instead of the raw video file, so tapping it — if EduInsta is installed —
   opens the app straight to that reel via Android App Links, instead of a
   browser. This is the other half: catching that incoming URL, both on a
   cold start (app wasn't running) and while the app is already open, and
   jumping straight to the reel it names. */
var pendingDeepLinkReelId=null;
function handleDeepLinkUrl(url){
  if(!url)return;
  const m=String(url).match(/\/reel\/([^/?#]+)/);
  if(!m)return;
  const id=Number(m[1]);
  if(!Number.isFinite(id))return;
  if(account&&account.loggedIn)openReel(id);
  else pendingDeepLinkReelId=id;   // opened once the user finishes logging in
}
function initDeepLinks(){
  const plugin=window.Capacitor?.Plugins?.App;
  if(!plugin?.addListener)return;
  plugin.addListener('appUrlOpen',(data)=>handleDeepLinkUrl(data?.url));
  // Cold start: the app may have been launched BY the deep link itself.
  plugin.getLaunchUrl?.().then(res=>handleDeepLinkUrl(res?.url)).catch(()=>{});
}

