function handleProfilePhoto(input){
  const file=input?.files?.[0]; if(!file)return;
  if(!file.type.startsWith('image/')){toast('Please select an image file');input.value='';return}
  if(file.size>10*1024*1024){toast('Please choose an image smaller than 10 MB');input.value='';return}
  const reader=new FileReader();
  reader.onerror=()=>toast('Could not read the image');
  reader.onload=()=>{
    const img=new Image();
    img.onerror=()=>toast('Could not process the image');
    img.onload=()=>{
      const max=512, scale=Math.min(1,max/Math.max(img.naturalWidth||1,img.naturalHeight||1));
      const c=document.createElement('canvas');
      c.width=Math.max(1,Math.round((img.naturalWidth||1)*scale));
      c.height=Math.max(1,Math.round((img.naturalHeight||1)*scale));
      const ctx=c.getContext('2d');
      if(!ctx){toast('Image processing is unavailable');return}
      ctx.drawImage(img,0,0,c.width,c.height);
      /* Local copy shows instantly on THIS device, even offline. */
      profile.avatarData=c.toDataURL('image/jpeg',.84);
      saveState(); toast('Profile photo updated'); editProfilePage();
      /* Server copy is what makes the photo visible to OTHER users - upload
         the same downscaled image in the background. Local display above
         already happened, so a slow/failed upload doesn't block the user. */
      c.toBlob(uploadProfilePhoto,'image/jpeg',.84);
    };
    img.src=reader.result;
  };
  reader.readAsDataURL(file);
}
